def style_header(ws):
    fill = PatternFill("solid", fgColor="8D4A28")
    font = Font(bold=True, color="FFFFFF", name="Calibri", size=11)
    thin = Border(
        left=Side(style="thin", color="D9D9D9"),
        right=Side(style="thin", color="D9D9D9"),
        top=Side(style="thin", color="D9D9D9"),
        bottom=Side(style="thin", color="D9D9D9"),
    )
    for col, h in enumerate(HEADERS, 1):
        cell = ws.cell(1, col, h)
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = thin
    ws.row_dimensions[1].height = 36
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(HEADERS))}1"


def status_fill(status: str) -> PatternFill | None:
    s = status.lower()
    if s.startswith("implemented"):
        return PatternFill("solid", fgColor="C6EFCE")
    if s.startswith("partial"):
        return PatternFill("solid", fgColor="FFEB9C")
    if s.startswith("missing"):
        return PatternFill("solid", fgColor="FFC7CE")
    if s.startswith("new"):
        return PatternFill("solid", fgColor="DDEBF7")
    return None


def write_sheet(ws, rows):
    style_header(ws)
    thin = Border(
        left=Side(style="thin", color="E0E0E0"),
        right=Side(style="thin", color="E0E0E0"),
        top=Side(style="thin", color="E0E0E0"),
        bottom=Side(style="thin", color="E0E0E0"),
    )
    wrap = Alignment(wrap_text=True, vertical="top")
    for r_idx, row in enumerate(rows, 2):
        for c_idx, val in enumerate(row, 1):
            cell = ws.cell(r_idx, c_idx, val)
            cell.alignment = wrap
            cell.border = thin
            cell.font = Font(name="Calibri", size=10)
        # color status column (10)
        sf = status_fill(str(row[9]))
        if sf:
            ws.cell(r_idx, 10).fill = sf
        # color priority
        pr = str(row[8]).upper()
        if pr == "P0":
            ws.cell(r_idx, 9).fill = PatternFill("solid", fgColor="F4B183")
        elif pr == "P1":
            ws.cell(r_idx, 9).fill = PatternFill("solid", fgColor="FFE699")
        ws.row_dimensions[r_idx].height = 110

    widths = [12, 18, 42, 22, 28, 55, 40, 36, 10, 22, 18, 32]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    # extend filter to data
    ws.auto_filter.ref = f"A1:{get_column_letter(len(HEADERS))}{len(rows) + 1}"

    dv = DataValidation(
        type="list",
        formula1='"Implemented,Partial,Missing,New (proposed)"',
        allow_blank=True,
    )
    ws.add_data_validation(dv)
    dv.add(f"J2:J{len(rows) + 1}")

    dv2 = DataValidation(type="list", formula1='"P0,P1,P2,P3"', allow_blank=True)
    ws.add_data_validation(dv2)
    dv2.add(f"I2:I{len(rows) + 1}")


