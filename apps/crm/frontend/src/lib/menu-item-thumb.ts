function normalize(s: string) {
  return s.toLowerCase().replace(/[^a-z0-9\s]/g, " ").replace(/\s+/g, " ").trim();
}

export function resolveMenuItemImageUrl(
  name: string,
  description: string | null | undefined,
  isVeg: boolean,
): string {
  const exact = EXACT_NAME[name.trim()];
  if (exact) return exact;

  const hay = normalize(`${name} ${description ?? ""}`);
  for (const rule of RULES) {
    if (rule.vegOnly && !isVeg) continue;
    if (rule.nonVegOnly && isVeg) continue;
    if (rule.keywords.some((k) => hay.includes(k))) return rule.url;
  }

  return isVeg ? THUMB.biryaniVeg : THUMB.biryani;
}

/** Prefer API `imageUrl` (catalog-backed). No generic biryani on unverified import drafts. */
export function menuItemThumb(item: {
  name: string;
  description?: string | null;
  isVeg: boolean;
  imageUrl?: string | null;
  draft?: boolean;
  importConfidence?: number | null;
}): string | null {
  if (item.imageUrl?.trim()) return item.imageUrl.trim();
  const lowConfDraft =
    item.draft && item.importConfidence != null && item.importConfidence < 70;
  if (lowConfDraft) return null;
  return resolveMenuItemImageUrl(item.name, item.description, item.isVeg);
}
